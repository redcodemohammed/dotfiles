#!/usr/bin/env python3
"""make-theme.py OUTDIR PALETTE.toml: the GRUB menu theme (owner's choice, 2026-10-15).

The lock and login screens' look: a solid background, a centred square box with a 2px border on
the surface colour, the selected entry filled with the accent, JetBrains Mono, a countdown and a
key hint under the box. Colours from palette.toml [ui], so it follows the wallpaper; sizes are for
the 2560x1600 laptop panel GRUB draws on (the desktop's sizes times its 4/3 scale). Writes
theme.txt, the styled-box PNGs (GRUB manual, "Styled Boxes": 9 slices, edges stretched) and the
fonts (grub-mkfont; grub-mkconfig loads every .pf2 next to theme.txt). Run by install.sh.
"""
import os
import subprocess
import sys
import tomllib

from PIL import Image

out, palette_path = sys.argv[1], sys.argv[2]
with open(palette_path, "rb") as f:
    ui = tomllib.load(f)["ui"]
os.makedirs(out, exist_ok=True)

FONT = "/usr/share/fonts/TTF/JetBrainsMonoNerdFont-Regular.ttf"
FAMILY = "JetBrains Mono"
SIZES = {"item": 20, "small": 16}  # px; 15 and 12 on the desktop at 4/3
BORDER = 2
PAD = 12  # inside the box, around the entries
EDGE = BORDER + PAD


def rgb(hex_colour):
    return tuple(int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))


def box(prefix, fill, border):
    """Nine slices: corners and edges EDGE thick (2px border outside, then fill), 1px centre."""
    slices = {"nw": (EDGE, EDGE), "n": (1, EDGE), "ne": (EDGE, EDGE), "w": (EDGE, 1), "c": (1, 1),
              "e": (EDGE, 1), "sw": (EDGE, EDGE), "s": (1, EDGE), "se": (EDGE, EDGE)}
    for name, (w, h) in slices.items():
        img = Image.new("RGB", (w, h), rgb(fill))
        px = img.load()
        for x in range(w):
            for y in range(h):
                if (("n" in name and y < BORDER) or ("s" in name and y >= h - BORDER)
                        or ("w" in name and x < BORDER) or ("e" in name and x >= w - BORDER)):
                    px[x, y] = rgb(border)
        img.save(os.path.join(out, f"{prefix}_{name}.png"))


box("menu", ui["surface"], ui["border"])
Image.new("RGB", (1, 1), rgb(ui["accent"])).save(os.path.join(out, "select_c.png"))  # flat, square

# Basic Latin and Latin-1, the arrows and the middle dot of the hint: small bitmap fonts.
for name, size in SIZES.items():
    subprocess.run(["grub-mkfont", "-s", str(size), "-n", FAMILY,
                    "-r", "0x20-0x7E,0xA0-0x17F,0x2022-0x2022,0x2190-0x2193",
                    "-o", os.path.join(out, f"jetbrains-{size}.pf2"), FONT], check=True)
item_font = f"{FAMILY} Regular {SIZES['item']}"
small_font = f"{FAMILY} Regular {SIZES['small']}"

W, ITEM_H, SPACING, ROWS = 640, 54, 4, 4  # four entries: Arch, Advanced, Windows, UEFI (GRUB scrolls if more)
H = 2 * EDGE + ROWS * ITEM_H + (ROWS - 1) * SPACING
theme = f"""# Generated by grub/make-theme.py from palette/palette.toml. Do not edit.
title-text: ""
desktop-color: "{ui['bg']}"
terminal-font: "{item_font}"
terminal-left: "0"
terminal-top: "0"
terminal-width: "100%"
terminal-height: "100%"
terminal-border: "0"

+ boot_menu {{
  left = 50%-{W // 2}
  top = 50%-{H // 2}
  width = {W}
  height = {H}
  menu_pixmap_style = "menu_*.png"
  selected_item_pixmap_style = "select_*.png"
  item_font = "{item_font}"
  item_color = "{ui['fg']}"
  selected_item_color = "{ui['on_accent']}"
  item_height = {ITEM_H}
  item_padding = 16
  item_spacing = {SPACING}
  icon_width = 0
  icon_height = 0
  item_icon_space = 0
  scrollbar = false
}}

+ label {{
  left = 50%-{W // 2}
  top = 50%+{H // 2 + 20}
  width = {W}
  align = "center"
  id = "__timeout__"
  text = "Booting in %d s"
  font = "{small_font}"
  color = "{ui['fg_muted']}"
}}

+ label {{
  left = 50%-{W // 2}
  top = 50%+{H // 2 + 52}
  width = {W}
  align = "center"
  text = "↑↓ select · Enter boot · e edit · c console"
  font = "{small_font}"
  color = "{ui['fg_dim']}"
}}
"""
with open(os.path.join(out, "theme.txt"), "w") as f:
    f.write(theme)

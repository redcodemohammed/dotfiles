#!/usr/bin/env python3
"""Generate app color files from palette.toml. Rerun after editing the palette."""
import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "Generated by palette/generate.py from palette/palette.toml. Do not edit."


# QML reads onXxx as a signal handler, so those names need another spelling.
QML_RENAMES = {"on_accent": "textOnAccent"}


def camel(name):
    if name in QML_RENAMES:
        return QML_RENAMES[name]
    head, *rest = name.split("_")
    return head + "".join(word.capitalize() for word in rest)


def theme_qml(palette):
    props = "\n".join(
        f'    readonly property color {camel(name)}: "{value}"'
        for name, value in palette["ui"].items()
    )
    return f"// {HEADER}\npragma Singleton\nimport QtQuick\nimport Quickshell\n\nSingleton {{\n{props}\n}}\n"


def alacritty_colors(palette):
    ui = palette["ui"]
    sections = {
        "primary": {"background": ui["bg"], "foreground": ui["fg"]},
        # Amber block cursor, dark glyph under it.
        "cursor": {"cursor": ui["accent"], "text": ui["on_accent"]},
        # Selection is a surface shade, never amber. Text keeps its own color.
        "selection": {"background": ui["surface_selected"], "text": "CellForeground"},
        "normal": palette["ansi"]["normal"],
        "bright": palette["ansi"]["bright"],
    }
    body = "\n\n".join(
        f"[colors.{name}]\n" + "\n".join(f'{key} = "{value}"' for key, value in table.items())
        for name, table in sections.items()
    )
    return f"# {HEADER}\n\n{body}\n"


def nvim_palette(palette):
    def table(colors):
        return "\n".join(f'    {name} = "{value}",' for name, value in colors.items())

    return (
        f"-- {HEADER}\nreturn {{\n"
        + "".join(
            f"  {section} = {{\n{table(colors)}\n  }},\n"
            for section, colors in (
                ("ui", palette["ui"]),
                ("normal", palette["ansi"]["normal"]),
                ("bright", palette["ansi"]["bright"]),
            )
        )
        + "}\n"
    )


def tmux_colors(palette):
    ui, n, b = palette["ui"], palette["ansi"]["normal"], palette["ansi"]["bright"]
    # tmux 3.6+ keeps its own theme palette (themegreen etc), separate from ANSI.
    theme = {
        "black": n["black"], "white": n["white"], "light-grey": ui["fg_muted"],
        "dark-grey": ui["border"], "green": n["green"], "yellow": n["yellow"],
        "red": n["red"], "blue": n["blue"], "cyan": n["cyan"], "magenta": n["magenta"],
    }
    styles = {
        "status-style": f"fg={ui['fg_muted']},bg={ui['bg']}",
        "window-status-style": f"fg={ui['fg_muted']},bg={ui['bg']}",
        # Active window: amber fill, dark text, like the active workspace.
        "window-status-current-style": f"fg={ui['on_accent']},bg={ui['accent']}",
        "pane-border-style": f"fg={ui['border']}",
        "pane-active-border-style": f"fg={ui['accent']}",
        "message-style": f"fg={ui['fg']},bg={ui['surface']}",
        "message-command-style": f"fg={ui['fg']},bg={ui['surface']}",
        "mode-style": f"fg={ui['fg']},bg={ui['surface_selected']}",
    }
    lines = [f'set -s dark-theme-{name} "{value}"' for name, value in theme.items()]
    lines += [f'set -g {name} "{value}"' for name, value in styles.items()]
    return f"# {HEADER}\n\n" + "\n".join(lines) + "\n"


def vicinae_theme(palette):
    ui, n = palette["ui"], palette["ansi"]["normal"]
    tables = {
        "meta": {
            "name": "Hypr", "description": "Shared palette", "variant": "dark",
            "inherits": "vicinae-dark",
        },
        "colors.core": {
            "accent": ui["accent"], "accent_foreground": ui["on_accent"],
            "background": ui["surface"], "foreground": ui["fg"],
            "secondary_background": ui["surface"], "border": ui["border"],
        },
        "colors.main_window": {"border": ui["border"]},
        "colors.settings_window": {"border": ui["border"]},
        "colors.accents": {
            "blue": n["blue"], "green": n["green"], "magenta": n["magenta"],
            "orange": n["yellow"], "red": n["red"], "yellow": n["yellow"],
            "cyan": n["cyan"], "purple": n["magenta"],
        },
        "colors.shortcut": {"border": ui["border"]},
        "colors.text": {
            "default": ui["fg"], "muted": ui["fg_muted"], "danger": ui["alert"],
            "success": n["green"], "placeholder": ui["fg_muted"],
        },
        # Text selection is a surface shade, never amber.
        "colors.text.selection": {"background": ui["surface_selected"], "foreground": ui["fg"]},
        "colors.text.links": {"default": n["blue"], "visited": n["magenta"]},
        # Typing border is amber, like the lock screen field.
        "colors.input": {
            "border": ui["border"], "border_focus": ui["accent"], "border_error": ui["alert"],
        },
        "colors.button.primary": {"background": ui["surface_selected"], "foreground": ui["fg"]},
        "colors.button.primary.hover": {"background": ui["border"]},
        "colors.button.primary.focus": {"outline": ui["accent"]},
        "colors.list.item.hover": {"foreground": ui["fg"], "secondary_foreground": ui["fg"]},
        # Selected row: lighter surface. No amber fill.
        "colors.list.item.selection": {
            "background": ui["surface_selected"], "foreground": ui["fg"],
            "secondary_background": ui["surface_selected"], "secondary_foreground": ui["fg"],
        },
        "colors.grid.item": {"background": ui["surface"]},
        "colors.grid.item.hover": {"outline": ui["border"]},
        "colors.grid.item.selection": {"outline": ui["accent"]},
        "colors.scrollbars": {"background": ui["border"]},
        "colors.loading": {"bar": ui["fg_muted"], "spinner": ui["fg_muted"]},
    }
    body = "\n\n".join(
        f"[{name}]\n" + "\n".join(f'{key} = "{value}"' for key, value in table.items())
        for name, table in tables.items()
    )
    return f"# {HEADER}\n\n{body}\n"


def satty_config(palette):
    ui = palette["ui"]
    # Amber first: the default annotation color. Satty wants #RRGGBBAA.
    swatches = ", ".join(f'"{ui[name]}ff"' for name in ("accent", "alert", "fg", "bg"))
    return f"""# {HEADER}

[general]
corner-roundness = 0
default-round-caps = false
initial-tool = "arrow"
copy-command = "wl-copy"
no-window-decoration = true

[font]
family = "JetBrainsMono Nerd Font"
style = "Regular"

[color-palette]
palette = [{swatches}]
"""


def hypr_palette(palette):
    # Hyprland color strings, e.g. rgb(f5a524).
    colors = "\n".join(f'    {name} = "rgb({value[1:]})",' for name, value in palette["ui"].items())
    return f"-- {HEADER}\nreturn {{\n{colors}\n}}\n"


def keyboard_env(palette):
    # openrgb-kb.service reads KB_COLOR. The keyboard's direct mode has no brightness control,
    # so the accent is scaled until its brightest channel is 255: same hue, full light.
    rgb = [int(palette["ui"]["accent"][i:i + 2], 16) for i in (1, 3, 5)]
    peak = max(rgb) or 1
    color = "".join(f"{round(c * 255 / peak):02X}" for c in rgb)
    return f"# {HEADER}\nKB_COLOR={color}\n"


def gtk_roles(palette):
    # libadwaita color roles -> palette. Same mapping for GTK3 (adw-gtk3) and GTK4.
    ui, n = palette["ui"], palette["ansi"]["normal"]
    return {
        "window_bg": ui["surface"], "window_fg": ui["fg"],
        "view_bg": ui["bg"], "view_fg": ui["fg"],
        "headerbar_bg": ui["surface"], "headerbar_fg": ui["fg"],
        "headerbar_border": ui["border"], "headerbar_backdrop": ui["surface"],
        "sidebar_bg": ui["bg"], "sidebar_fg": ui["fg"],
        "sidebar_border": ui["border"], "sidebar_backdrop": ui["bg"],
        "card_bg": ui["surface_selected"], "card_fg": ui["fg"],
        "dialog_bg": ui["surface"], "dialog_fg": ui["fg"],
        "popover_bg": ui["surface"], "popover_fg": ui["fg"],
        "accent_bg": ui["accent"], "accent_fg": ui["on_accent"], "accent": ui["accent"],
        "destructive_bg": ui["alert"], "destructive_fg": ui["fg"], "destructive": ui["alert"],
        "error_bg": ui["alert"], "error_fg": ui["fg"], "error": ui["alert"],
        # No amber warnings: amber means focus, never caution.
        "warning_bg": ui["border"], "warning_fg": ui["fg"], "warning": ui["fg"],
        "success_bg": n["green"], "success_fg": ui["bg"], "success": n["green"],
    }


GTK_SHAPE = """
/* Sharp and flat: no rounding, no window shadows. */
* { border-radius: 0; }
decoration, window.csd { box-shadow: none; }
"""


def spotifast_theme(palette):
    # Spotifast palette, listed as "Hypr" in Settings > Appearance > Theme. Same roles as gtk_roles.
    # JSON has no comments, so this file carries no HEADER.
    ui, bright = palette["ui"], palette["ansi"]["bright"]
    colors = {
        "window": ui["surface"], "panel": ui["bg"], "surface": ui["surface_selected"],
        "surface_hover": ui["border"], "surface_active": ui["border"], "outline": ui["border"],
        "text": ui["fg"], "secondary": ui["fg_muted"], "dim": ui["fg_dim"],
        "accent": ui["accent"], "accent_hover": bright["yellow"], "on_accent": ui["on_accent"],
        "danger": ui["alert"],
        "warning": ui["fg"],  # No amber warnings: amber means focus, never caution.
        "shadow": "#00000000",  # No shadows.
    }
    return json.dumps({"base": "dark", "colors": colors}, indent=2) + "\n"


def gtk3_css(palette):
    colors = "\n".join(f"@define-color {role}_color {value};" for role, value in gtk_roles(palette).items())
    return f"/* {HEADER} */\n/* GTK3 via adw-gtk3: overrides its named colors. */\n{colors}\n@define-color borders {palette['ui']['border']};\n{GTK_SHAPE}"


def gtk4_css(palette):
    variables = "\n".join(
        f"    --{role.replace('_', '-')}-color: {value};" for role, value in gtk_roles(palette).items()
    )
    return (
        f"/* {HEADER} */\n/* GTK4 / libadwaita 1.10: CSS variables. */\n:root {{\n{variables}\n"
        f"    --border-color: {palette['ui']['border']};\n    --window-radius: 0;\n}}\n{GTK_SHAPE}"
    )


# Paths are relative to the repo root, which mirrors $HOME (stow layout).
OUTPUTS = {
    ".config/gtk-3.0/gtk.css": gtk3_css,
    ".config/gtk-4.0/gtk.css": gtk4_css,
    ".config/hypr/hypr_palette.lua": hypr_palette,
    ".config/satty/config.toml": satty_config,
    ".local/share/vicinae/themes/hypr.toml": vicinae_theme,
    ".config/tmux/colors.conf": tmux_colors,
    ".config/quickshell/Theme.qml": theme_qml,
    ".config/alacritty/colors.toml": alacritty_colors,
    ".config/nvim/lua/hypr_palette.lua": nvim_palette,
    ".config/openrgb-kb/color.env": keyboard_env,
    "spotifast/Hypr.json": spotifast_theme,  # not stowed: see COPIES
}

# Apps that skip symlinked files get a real copy in $HOME; the repo file stays the tracked source.
# Written only when the content differs, so setup/check.sh changes nothing when up to date.
COPIES = {
    "spotifast/Hypr.json": "~/.config/spotifast/themes/Hypr.json",
}


def main():
    palette = tomllib.loads((ROOT / "palette/palette.toml").read_text())
    for path, render in OUTPUTS.items():
        out = ROOT / path
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(render(palette))
        print(f"wrote {path}")
    for src, dest in COPIES.items():
        out, data = Path(dest).expanduser(), (ROOT / src).read_bytes()
        if out.exists() and out.read_bytes() == data:
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)
        print(f"copied {src} -> {dest}")


if __name__ == "__main__":
    main()

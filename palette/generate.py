# QML reads onXxx as a signal handler, so those names need another spelling.
QML_RENAMES = {"on_accent": "textOnAccent"}


def camel(name):
    if name in QML_RENAMES:
        return QML_RENAMES[name]
    head, *rest = name.split("_")
    return head + "".join(word.capitalize() for word in rest)


def theme_qml(palette):
    props = "\n".join(
        f'    readonly property color {camel(name)}: "{value}"'
        for name, value in palette["ui"].items()
    )
    return f"// {HEADER}\npragma Singleton\nimport QtQuick\nimport Quickshell\n\nSingleton {{\n{props}\n}}\n"


def alacritty_colors(palette):
    ui = palette["ui"]
    sections = {
        "primary": {"background": ui["bg"], "foreground": ui["fg"]},
        # Amber block cursor, dark glyph under it.
        "cursor": {"cursor": ui["accent"], "text": ui["on_accent"]},
        # Selection is a surface shade, never amber. Text keeps its own color.
        "selection": {"background": ui["surface_selected"], "text": "CellForeground"},
        "normal": palette["ansi"]["normal"],
        "bright": palette["ansi"]["bright"],
    }
    body = "\n\n".join(
        f"[colors.{name}]\n" + "\n".join(f'{key} = "{value}"' for key, value in table.items())
        for name, table in sections.items()
    )
    return f"# {HEADER}\n\n{body}\n"


def nvim_palette(palette):
    def table(colors):
        return "\n".join(f'    {name} = "{value}",' for name, value in colors.items())

    return (
        f"-- {HEADER}\nreturn {{\n"
        + "".join(
            f"  {section} = {{\n{table(colors)}\n  }},\n"
            for section, colors in (
                ("ui", palette["ui"]),
                ("normal", palette["ansi"]["normal"]),
                ("bright", palette["ansi"]["bright"]),
            )
        )
        + "}\n"
    )



#!/usr/bin/env python3
"""make-theme.py OUTDIR PALETTE.toml: the Plymouth boot splash (owner's choice, 2026-10-15).

The GRUB menu's and login screen's look: the palette background, the Arch logo in the accent
colour above the centre, three small accent squares under it pulsing in turn. Boot messages
(fsck and such) show muted at the bottom in JetBrains Mono, and anything asking for a password
gets a plain prompt with bullets. Sizes for the 2560x1600 laptop panel. Writes hypr.plymouth,
hypr.script, logo.png and square.png. Run by install.sh.
"""
import os
import re
import subprocess
import sys
import tomllib

from PIL import Image

out, palette_path = sys.argv[1], sys.argv[2]
with open(palette_path, "rb") as f:
    ui = tomllib.load(f)["ui"]
os.makedirs(out, exist_ok=True)

LOGO_SVG = "/usr/share/pixmaps/archlinux-logo.svg"  # one fill, #1793d1
LOGO = 112  # px
SQUARE = 12  # px, 12px apart

with open(LOGO_SVG) as f:
    svg = f.read().replace("#1793d1", ui["accent"])
# The pixmap's first <path> is the logo; the others draw a small trademark sign beside it.
paths = re.findall(r"<path\b.*?/>", svg, flags=re.S)
for extra in paths[1:]:
    svg = svg.replace(extra, "")
subprocess.run(["rsvg-convert", "-w", str(LOGO), "-h", str(LOGO), "-o", os.path.join(out, "logo.png")],
               input=svg.encode(), check=True)
Image.new("RGB", (SQUARE, SQUARE), ui["accent"]).save(os.path.join(out, "square.png"))


def rgb(hex_colour):
    return ", ".join(f"{int(hex_colour[i:i + 2], 16) / 255:.3f}" for i in (1, 3, 5))


with open(os.path.join(out, "hypr.plymouth"), "w") as f:
    f.write(f"""[Plymouth Theme]
Name=Hypr
Description=Palette background, Arch logo, three pulsing squares (dotfiles plymouth/make-theme.py)
ModuleName=script

[script]
ImageDir=/usr/share/plymouth/themes/hypr
ScriptFile=/usr/share/plymouth/themes/hypr/hypr.script
Font=JetBrainsMono Nerd Font 12
MonospaceFont=JetBrainsMono Nerd Font 12
""")

with open(os.path.join(out, "hypr.script"), "w") as f:
    f.write(f"""# Generated by plymouth/make-theme.py from palette/palette.toml. Do not edit.
Window.SetBackgroundTopColor({rgb(ui['bg'])});
Window.SetBackgroundBottomColor({rgb(ui['bg'])});

cx = Window.GetX() + Window.GetWidth() / 2;
cy = Window.GetY() + Window.GetHeight() / 2;

logo.image = Image("logo.png");
logo.sprite = Sprite(logo.image);
logo.sprite.SetPosition(cx - logo.image.GetWidth() / 2, cy - logo.image.GetHeight() + 16, 1);

square_image = Image("square.png");
for (i = 0; i < 3; i++)
  {{
    squares[i] = Sprite(square_image);
    squares[i].SetPosition(cx - 30 + i * 24, cy + 64, 1);
  }}

time = 0;
fun refresh_callback ()
  {{
    time++;  # 50 per second
    for (i = 0; i < 3; i++)
      {{
        phase = time / 50 * 2 * 3.14159 / 1.2 - i * 0.9;  # 1.2 s per pulse, each square a step later
        squares[i].SetOpacity(0.25 + 0.75 * (Math.Cos(phase) + 1) / 2);
      }}
  }}
Plymouth.SetRefreshFunction (refresh_callback);

# Messages (fsck and such): muted, centred near the bottom.
message.sprite = Sprite();
fun display_message_callback (text)
  {{
    message.image = Image.Text(text, {rgb(ui['fg_muted'])});
    message.sprite.SetImage(message.image);
    message.sprite.SetPosition(cx - message.image.GetWidth() / 2, Window.GetY() + Window.GetHeight() - 96, 2);
  }}
fun hide_message_callback (text)
  {{
    message.sprite.SetOpacity(0);
    message.sprite = Sprite();
  }}
Plymouth.SetDisplayMessageFunction (display_message_callback);
Plymouth.SetHideMessageFunction (hide_message_callback);

# A password request (none expected: no disk encryption): the prompt and one bullet per key.
prompt.sprite = Sprite();
fun display_password_callback (text, bullets)
  {{
    line = text + "  ";
    for (i = 0; i < bullets; i++)
      line = line + "*";
    prompt.image = Image.Text(line, {rgb(ui['fg'])});
    prompt.sprite.SetImage(prompt.image);
    prompt.sprite.SetPosition(cx - prompt.image.GetWidth() / 2, cy + 120, 2);
    prompt.sprite.SetOpacity(1);
  }}
fun display_normal_callback ()
  {{
    prompt.sprite.SetOpacity(0);
  }}
Plymouth.SetDisplayPasswordFunction (display_password_callback);
Plymouth.SetDisplayNormalFunction (display_normal_callback);
""")
